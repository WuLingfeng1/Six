#!/usr/bin/env python3
"""Generate source fingerprints and config serialization for the compiled worker."""
import argparse
import hashlib
import json
from pathlib import Path

from config_tools import FIELD, SHAPE_FIELDS, config_block

parser = argparse.ArgumentParser()
parser.add_argument("source", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
header = (args.source / "Game.h").read_bytes()
fields = [(m[1].decode(), m[2].decode()) for m in FIELD.finditer(config_block(header)[1])]
names = {name for _, name in fields}
hashes = {name: hashlib.sha256((args.source / name).read_bytes()).hexdigest()
          for name in ("Game.cpp", "Game.h", "Move.cpp", "Move.h")}
for name in ("self_iteration.cpp", "openings.h"):
    hashes[name] = hashlib.sha256(Path(__file__).with_name(name).read_bytes()).hexdigest()
lines = ["// Generated by build_manifest.py. Do not edit.", "#pragma once",
         "#define SIX_HAS_SEARCH_STATS %d" % (b"searchStats() const" in header),
         "#define SIX_HAS_INCREMENTAL_TACTICS %d" % ("incrementalTactics" in names),
         "#define SIX_HAS_SHAPE_WEIGHTS %d" % set(SHAPE_FIELDS).issubset(names),
         "#define SIX_HAS_THREAT_EXTENSION %d" % ("threatExtension" in names),
         "inline QJsonObject compiledSourceHashes() { return QJsonObject{"]
lines += ['    {%s, %s},' % (json.dumps(k), json.dumps(v)) for k, v in sorted(hashes.items())]
lines += ["}; }", "inline QJsonObject searchConfigJson() { return QJsonObject{"]
for kind, name in fields:
    value = "Game::searchConfig." + name
    if kind == "qint64":
        value = "double(" + value + ")"
    lines.append('    {"%s", %s},' % (name, value))
lines += ["}; }", ""]
data = "\n".join(lines)
if not args.output.exists() or args.output.read_text() != data:
    args.output.write_text(data)
